const files = readdirSync(DAY_DIR).filter((f) => /^day\d+\.js$/.test(f))

let totalReplacements = 0
const summary = []

for (const file of files) {
  const path = join(DAY_DIR, file)
  const original = readFileSync(path, 'utf8')
  let text = original
  let fileReplacements = 0

  for (const [from, to] of REPLACEMENTS) {
    if (from === to) continue
    const parts = text.split(from)
    if (parts.length > 1) {
      fileReplacements += parts.length - 1
      text = parts.join(to)
    }
  }

  if (text !== original) {
    writeFileSync(path, text)
    summary.push(`  ${file}: ${fileReplacements} replacements`)
    totalReplacements += fileReplacements
  }
}

console.log(`Wellness rewording complete: ${totalReplacements} total replacements across ${summary.length} files`)
